
from io import BytesIO
from docx import Document
from docx.shared import Inches, Pt, RGBColor


def generate_comparison_report(
    document_a,
    document_b,
    summary_a,
    summary_b,
    comparison,
):
    """Create a downloadable Word report for two compared PDFs."""

    report = Document()

    # Page layout
    section = report.sections[0]
    section.top_margin = Inches(0.7)
    section.bottom_margin = Inches(0.7)
    section.left_margin = Inches(0.8)
    section.right_margin = Inches(0.8)

    # Default font
    styles = report.styles
    styles["Normal"].font.name = "Aptos"
    styles["Normal"].font.size = Pt(10)

    # Title
    title = report.add_heading(
        "AI Document Comparison Report",
        level=0,
    )
    title.alignment = 1

    report.add_paragraph(
        "Generated by AI Document Comparison Assistant"
    )

    # Document information
    report.add_heading("1. Document Information", level=1)
    report.add_paragraph(
        f"Document A: {document_a.get('filename', 'Document A')}"
    )
    report.add_paragraph(
        f"Pages: {document_a.get('page_count', 'Unknown')}"
    )
    report.add_paragraph(
        f"Document B: {document_b.get('filename', 'Document B')}"
    )
    report.add_paragraph(
        f"Pages: {document_b.get('page_count', 'Unknown')}"
    )

    # Individual summaries
    report.add_heading("2. Individual Document Summaries", level=1)

    report.add_heading("Document A Summary", level=2)
    report.add_paragraph(summary_a.get("summary", "No summary available."))

    report.add_heading("Document A Key Points", level=3)
    add_items(report, summary_a.get("key_points", []))

    report.add_heading("Document B Summary", level=2)
    report.add_paragraph(summary_b.get("summary", "No summary available."))

    report.add_heading("Document B Key Points", level=3)
    add_items(report, summary_b.get("key_points", []))

    # Overview
    report.add_heading("3. Overall Comparison", level=1)
    report.add_paragraph(
        comparison.get("overview", "No overview available.")
    )

    # Similarities
    report.add_heading("4. Similarities", level=1)
    add_comparison_items(
        report,
        comparison.get("similarities", []),
        "No similarities were identified.",
    )

    # Differences
    report.add_heading("5. Differences", level=1)
    add_comparison_items(
        report,
        comparison.get("differences", []),
        "No differences were identified.",
    )

    # Key details
    report.add_heading("6. Important Details", level=1)
    add_comparison_items(
        report,
        comparison.get("key_details", []),
        "No additional key details were identified.",
    )

    # Conclusion
    report.add_heading("7. Conclusion", level=1)
    report.add_paragraph(
        comparison.get("conclusion", "No conclusion available.")
    )

    # Limitations
    report.add_heading("8. Limitations", level=1)
    limitations = comparison.get("limitations", [])

    if limitations:
        add_items(report, limitations)
    else:
        report.add_paragraph(
            "The report is based on the readable text extracted "
            "from the two uploaded PDFs. Verify important findings "
            "against the original documents."
        )

    # Footer
    for current_section in report.sections:
        footer = current_section.footer.paragraphs[0]
        footer.text = (
            "AI Document Comparison Assistant | "
            "Review findings against the original documents."
        )
        footer.alignment = 1

    # Return the Word document as bytes for downloading
    output = BytesIO()
    report.save(output)
    output.seek(0)

    return output.getvalue()


def add_items(report, items):
    """Add a list of strings or details to a Word document."""

    if not items:
        report.add_paragraph("No items available.")
        return

    for item in items:
        if isinstance(item, dict):
            text = item.get("detail") or str(item)
        else:
            text = str(item)

        report.add_paragraph(text, style="List Bullet")


def add_comparison_items(report, items, empty_message):
    """Add comparison objects with their available fields."""

    if not items:
        report.add_paragraph(empty_message)
        return

    for index, item in enumerate(items, start=1):
        if not isinstance(item, dict):
            report.add_paragraph(str(item), style="List Bullet")
            continue

        topic = item.get("topic", f"Item {index}")
        report.add_heading(str(topic), level=2)

        for key, value in item.items():
            if key == "topic":
                continue

            label = key.replace("_", " ").capitalize()

            if isinstance(value, list):
                value = "; ".join(str(part) for part in value)

            paragraph = report.add_paragraph()
            paragraph.add_run(f"{label}: ").bold = True
            paragraph.add_run(str(value))
